async function seedTopics() {
  console.log("Starting Computer Science topic seeding...");

  const domain = await upsertTopic(
    "Computer Science",
    "computer-science",
    "DOMAIN",
    null,
    1
  );

  for (const [categoryIndex, categoryData] of categories.entries()) {
    const category = await upsertTopic(
      categoryData.name,
      categoryData.slug,
      "CATEGORY",
      domain.id,
      categoryIndex + 1
    );

    console.log(`Processing category: ${category.name}`);

    for (const [topicIndex, topicName] of categoryData.topics.entries()) {
      const topicSlug = `${categoryData.slug}-${topicName
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, "")}`;

      await upsertTopic(
        topicName,
        topicSlug,
        "TOPIC",
        category.id,
        topicIndex + 1
      );
    }
  }

  console.log("Computer Science topics seeded successfully!");
}

seedTopics()
  .catch((error) => {
    console.error("Topic seeding failed:", error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
