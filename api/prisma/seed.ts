
import prisma from "../src/config/database.js";

type TopicLevel = "DOMAIN" | "CATEGORY" | "TOPIC";

async function upsertTopic(
  name: string,
  slug: string,
  level: TopicLevel,
  parentId: string | null,
  sortOrder: number
) {
  return prisma.topic.upsert({
    where: { slug },
    update: {
      name,
      level,
      parentId,
      isActive: true,
      sortOrder,
    },
    create: {
      name,
      slug,
      level,
      parentId,
      isActive: true,
      sortOrder,
    },
  });
}

